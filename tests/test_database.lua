H.Test("journal filters threat evidence and clearing history does not affect personal lists", function()
    local RG = addon()
    local db = RG.Database.New()
    local profile = db:GetProfile()
    local function record(id, evidence)
        local contact = { identity = "guid:" .. id, name = id, hostile = true, isPlayer = true }
        for key, value in pairs(evidence or {}) do contact[key] = value end
        db:Record(contact, 100, "Zone")
    end
    profile.retention.journalMode = "watched"
    record("Ordinary"); record("Threat only", { targeting = true })
    H.Equal(#db:GetJournal(), 0)
    record("Watch", { watched = true }); H.Equal(#db:GetJournal(), 1)
    profile.retention.journalMode = "threats"
    record("Suspected", { stealth = "suspected" }); H.Equal(#db:GetJournal(), 1)
    record("Confirmed stealth", { stealth = "confirmed" }); H.Equal(#db:GetJournal(), 2)
    record("Targeting", { targeting = true }); H.Equal(#db:GetJournal(), 3)
    assert(db:SetList("guid:Watch", "watch", "Private"))
    H.Equal(db:ClearJournal(), 3); H.Equal(#db:GetJournal(), 0)
    H.Equal(db:GetList()["guid:Watch"].note, "Private")
end)
